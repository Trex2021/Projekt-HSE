export type ChecklistSectorId = (typeof CHECKLIST_SECTORS)[number]["id"];

export interface ChecklistTemplate {
  id: string;
  sector: ChecklistSectorId;
  sectors: readonly ChecklistSectorId[];
  name: string;
  activity: string;
  description: string;
  keywords: readonly string[];
  items: readonly string[];
}

const checklist = (
  id: string,
  sector: ChecklistSectorId,
  name: string,
  activity: string,
  description: string,
  keywords: readonly string[],
  items: readonly string[],
  additionalSectors: readonly ChecklistSectorId[] = [],
): ChecklistTemplate => ({
  id,
  sector,
  sectors: [sector, ...additionalSectors.filter((item) => item !== sector)],
  name,
  activity,
  description,
  keywords,
  items,
});

