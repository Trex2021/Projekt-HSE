export const normalizeChecklistText = (value: string) =>
  value
    .normalize("NFKC")
    .toLocaleLowerCase("fa")
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[\u064b-\u065f\u0670]/g, "")
    .replace(/[\u200c\u200e\u200f]/g, " ")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim();

export function filterChecklists(
  templates: readonly ChecklistTemplate[],
  query: string,
  sector: "all" | ChecklistSectorId = "all",
) {
  const terms = normalizeChecklistText(query).split(" ").filter(Boolean);
  return templates.filter((template) => {
    if (sector !== "all" && !template.sectors.includes(sector)) return false;
    if (!terms.length) return true;
    const searchable = normalizeChecklistText([
      template.name,
      template.activity,
      template.description,
      ...template.keywords,
      ...template.items,
    ].join(" "));
    return terms.every((term) => searchable.includes(term));
  });
}

export function getChecklistSector(sectorId: ChecklistSectorId) {
  return CHECKLIST_SECTORS.find((sector) => sector.id === sectorId) ?? CHECKLIST_SECTORS[0];
}

export function getChecklistSectors(template: ChecklistTemplate) {
  return template.sectors.map(getChecklistSector);
}
